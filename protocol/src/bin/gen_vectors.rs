//! Generates `vectors/v1.json`. Every input is a fixed byte pattern so the
//! file is reproducible; every output is what the spec requires.

use serde_json::{json, Value};
use sigil_protocol::*;

fn fill(b: u8, n: usize) -> Vec<u8> {
    vec![b; n]
}
fn a32(b: u8) -> [u8; 32] {
    [b; 32]
}
fn a24(b: u8) -> [u8; 24] {
    [b; 24]
}
fn h(b: &[u8]) -> String {
    hex::encode(b)
}

fn main() {
    let mut v = serde_json::Map::new();
    v.insert("version".into(), json!(1));
    v.insert(
        "note".into(),
        json!("Sigil Protocol v1 test vectors. Generated by `cargo run --bin gen-vectors` in protocol/. Inputs are fixed byte patterns; outputs are normative."),
    );

    // 1. hash and kdf
    v.insert(
        "kdf".into(),
        json!({
            "hash_empty": h(&kdf::hash(b"")),
            "hash_sigil": h(&kdf::hash(b"sigil")),
            "kdf_ctx": "sigil v1 test",
            "kdf_ikm": h(b"abc"),
            "kdf_out": h(&kdf::kdf("sigil v1 test", b"abc")),
            "kdf_n_64": h(&kdf::kdf_n("sigil v1 test", b"abc", 64)),
        }),
    );

    // 2. kem
    let sk = kem::keypair(&a32(0x01));
    let (ct, ss) = kem::encapsulate(sk.public(), &a32(0x02)).unwrap();
    assert_eq!(sk.decapsulate(&ct).unwrap(), ss);
    v.insert(
        "kem".into(),
        json!({
            "seed": h(&a32(0x01)),
            "public_key": h(sk.public()),
            "eseed": h(&a32(0x02)),
            "ciphertext": h(&ct),
            "shared_secret": h(&ss),
        }),
    );

    // 3. identity and card
    let id = identity::Identity::from_seed(&a32(0x03));
    let fp = identity::fingerprint(&id.public());
    let card = identity::ContactCard {
        username: "@alice:sigil.example".into(),
        identity_pub: id.public(),
        kem_pub: id.kem.public().to_vec(),
        slot_server: "sigil.example".into(),
        flags: 1,
    };
    let signed = card.sign(&id);
    assert_eq!(identity::ContactCard::verify(&signed).unwrap(), card);
    v.insert(
        "identity".into(),
        json!({
            "seed": h(&a32(0x03)),
            "identity_pub": h(&id.public()),
            "kem_pub": h(id.kem.public()),
            "fingerprint": h(&fp),
            "fingerprint_display": identity::fingerprint_display(&fp),
            "card": {
                "username": card.username,
                "slot_server": card.slot_server,
                "flags": card.flags,
                "signed": h(&signed),
            }
        }),
    );

    // 4. names
    let period = 689u32;
    let req_addr = names::requests_address(&id.public(), period);
    let proof = names::requests_read_proof(&id.signing, &req_addr, &a32(0x04));
    names::verify_requests_read_proof(&id.public(), &req_addr, &a32(0x04), &proof).unwrap();
    v.insert("names".into(), json!({
        "identity_pub": h(&id.public()),
        "shelf_address": h(&names::shelf_address(&id.public())),
        "shelf_key": h(&names::shelf_key(&id.public())),
        "requests_period": period,
        "requests_address": h(&req_addr),
        "requests_read_nonce": h(&a32(0x04)),
        "requests_read_proof": h(&proof),
        "valid_usernames": ["@alice:sigil.example", "@a.b_c-1:x.y"],
        "invalid_usernames": ["alice:sigil.example", "@Alice:sigil.example", "@alice:localhost", "@.alice:x.y", "@:x.y", "@alice:x.y:z"],
    }));

    // 5. epoch and 6. envelope
    let ep = epoch::derive(&a32(0x05));
    let event = envelope::Event {
        kind: envelope::Kind::Text as u16,
        ts_ms: 1_756_684_800_000,
        reference: vec![],
        body: b"hello, world".to_vec(),
    };
    let enc = event.encode();
    let sealed = envelope::seal(&ep.envelope_key, &ep.address, &a24(0x06), &enc).unwrap();
    assert_eq!(
        envelope::open(&ep.envelope_key, &ep.address, &sealed).unwrap(),
        enc
    );
    let put_sig = epoch::sign_put(&ep.write_key, &ep.address, &sealed);
    epoch::verify_put(&ep.write_pub, &ep.address, &sealed, &put_sig).unwrap();
    v.insert(
        "epoch".into(),
        json!({
            "epoch_secret": h(&a32(0x05)),
            "slot_seed": h(&ep.slot_seed),
            "read_cap": h(&ep.read_cap),
            "write_seed": h(&ep.write_key.to_bytes()),
            "write_pub": h(&ep.write_pub),
            "address": h(&ep.address),
            "envelope_key": h(&ep.envelope_key),
            "call_room": h(&ep.call_room),
        }),
    );
    v.insert("envelope".into(), json!({
        "event": { "kind": event.kind, "ts_ms": event.ts_ms, "reference": "", "body": h(&event.body) },
        "event_encoded": h(&enc),
        "padded": h(&envelope::pad(&enc).unwrap()),
        "nonce": h(&a24(0x06)),
        "envelope": h(&sealed),
        "put_signature": h(&put_sig),
        "bucket_lengths": { "plaintext_max": [984, 4056, 16344], "envelope": [1024, 4096, 16384] },
    }));

    // 7. bag
    let server = kem::keypair(&a32(0x07));
    let (bag_bytes, k) =
        bag::seal_request(server.public(), &a32(0x08), &a24(0x09), b"ping").unwrap();
    let (req, k2) = bag::open_request(&server, &bag_bytes).unwrap();
    assert_eq!(req, b"ping");
    assert_eq!(k.request, k2.request);
    let resp = bag::seal_response(&k2, &a24(0x0a), b"pong").unwrap();
    assert_eq!(bag::open_response(&k, &resp).unwrap(), b"pong");
    v.insert("bag".into(), json!({
        "server_seed": h(&a32(0x07)),
        "server_public_key": h(server.public()),
        "eseed": h(&a32(0x08)),
        "request_nonce": h(&a24(0x09)),
        "request": h(b"ping"),
        "request_key": h(&k.request),
        "response_key": h(&k.response),
        "bag": h(&bag_bytes),
        "response_nonce": h(&a24(0x0a)),
        "response": h(b"pong"),
        "response_sealed": h(&resp),
        "bucket_lengths": { "request": [2048, 8192, 32768], "response": [1024, 4096, 16384, 65536] },
    }));

    // 8. recovery
    let salt: [u8; 16] = [0x0b; 16];
    let pw = b"correct horse battery staple";
    let pw_key = recovery::password_key(pw, &salt);
    let rk = a32(0x0c);
    let bk = recovery::backup_key(&pw_key, &rk);
    let dk = a32(0x0d);
    let wrap = recovery::wrap_data_key(&bk, &a24(0x0e), &dk);
    assert_eq!(recovery::unwrap_data_key(&bk, &wrap).unwrap(), dk);
    let code = recovery::recovery_code(&rk);
    assert_eq!(recovery::parse_recovery_code(&code).unwrap(), rk);
    v.insert("recovery".into(), json!({
        "password": String::from_utf8_lossy(pw),
        "salt": h(&salt),
        "argon2id": { "m_kib": recovery::ARGON2_M_KIB, "t": recovery::ARGON2_T, "p": recovery::ARGON2_P, "out": 32 },
        "pw_key": h(&pw_key),
        "recovery_key": h(&rk),
        "backup_key": h(&bk),
        "data_key": h(&dk),
        "backup_label": h(&recovery::backup_label(&dk)),
        "wrap_nonce": h(&a24(0x0e)),
        "wrapped_data_key": h(&wrap),
        "tpm_auth": h(&recovery::tpm_auth(&pw_key)),
        "recovery_code": code,
    }));

    // 9. linking
    let new_dev = kem::keypair(&a32(0x0f));
    let offer = linking::LinkOffer {
        kem_pub: new_dev.public().to_vec(),
        nonce: [0x10; 16],
    };
    let offer_enc = offer.encode();
    let (lct, lss) = kem::encapsulate(&offer.kem_pub, &a32(0x11)).unwrap();
    assert_eq!(new_dev.decapsulate(&lct).unwrap(), lss);
    let lm = linking::derive(&lss, &offer);
    v.insert(
        "linking".into(),
        json!({
            "new_device_seed": h(&a32(0x0f)),
            "offer_nonce": h(&offer.nonce),
            "offer_encoded": h(&offer_enc),
            "offer_rendezvous": h(&linking::offer_rendezvous(&offer)),
            "existing_eseed": h(&a32(0x11)),
            "ciphertext": h(&lct),
            "shared": h(&lss),
            "link_secret": h(&lm.link_secret),
            "rendezvous": h(&lm.rendezvous),
            "link_key": h(&lm.link_key),
            "sas_indices": lm.sas.to_vec(),
            "sas": linking::sas_string(&lm.sas),
            "emoji_table": emoji::TABLE.to_vec(),
        }),
    );

    // 10. requests envelope (sealed to the recipient's identity KEM key)
    let bob = identity::Identity::from_seed(&a32(0x12));
    let req_address = names::requests_address(&bob.public(), 689);
    let welcome = b"welcome bytes stand in for an MLS Welcome";
    let req_env = requests::seal(
        bob.kem.public(),
        &req_address,
        &a32(0x13),
        &a24(0x14),
        welcome,
    )
    .unwrap();
    assert_eq!(
        requests::open(&bob.kem, &req_address, &req_env).unwrap(),
        welcome
    );
    v.insert(
        "requests_envelope".into(),
        json!({
            "recipient_seed": h(&a32(0x12)),
            "recipient_kem_pub": h(bob.kem.public()),
            "address": h(&req_address),
            "eseed": h(&a32(0x13)),
            "nonce": h(&a24(0x14)),
            "plain": h(welcome),
            "envelope": h(&req_env),
            "bucket_lengths": [4096, 16384],
        }),
    );

    // 11. tokens
    let mut rng = testrng::TestRng::new(b"token issuer");
    let issuer = token::Issuer::generate(&mut rng);
    let verifier = token::Verifier::from_spki(&issuer.spki).unwrap();
    let mut crng = testrng::TestRng::new(b"token client");
    let pending = verifier.blind(&mut crng, a32(0x15)).unwrap();
    let blind_sig = issuer.sign(&pending.blinded).unwrap();
    let tok = verifier.finalize(&pending, &blind_sig).unwrap();
    verifier.verify(&tok).unwrap();
    let tok_bytes = tok.encode();
    assert_eq!(token::Token::decode(&tok_bytes).unwrap(), tok);
    v.insert(
        "token".into(),
        json!({
            "issuer_secret_der": h(&issuer.to_der()),
            "issuer_spki": h(&issuer.spki),
            "key_id": h(&issuer.key_id),
            "nonce": h(&a32(0x15)),
            "message": h(&token::message(&issuer.key_id, &a32(0x15))),
            "blinding_secret": h(&pending.secret),
            "blinded": h(&pending.blinded),
            "blind_signature": h(&blind_sig),
            "signature": h(&tok.signature),
            "token": h(&tok_bytes),
            "spend_id": h(&tok.spend_id()),
        }),
    );

    // 12. wire: requests, responses, frames, server card
    let sample_token = tok_bytes.clone();
    let reqs = vec![
        (
            "slot.put",
            wire::Request::SlotPut {
                address: ep.address,
                write_pub: ep.write_pub,
                sig: put_sig,
                envelope: sealed.clone(),
                token: sample_token.clone(),
            },
        ),
        (
            "slot.get",
            wire::Request::SlotGet {
                read_cap: ep.read_cap,
                write_pub: ep.write_pub,
                after_seq: 41,
                limit: 50,
            },
        ),
        (
            "slot.ack",
            wire::Request::SlotAck {
                read_cap: ep.read_cap,
                write_pub: ep.write_pub,
                seq: 42,
            },
        ),
        (
            "slot.subscribe",
            wire::Request::SlotSubscribe {
                address: ep.address,
                wake_handle: a32(0x16),
                proof: vec![],
                token: sample_token.clone(),
            },
        ),
        (
            "slot.subscribe.requests",
            wire::Request::SlotSubscribe {
                address: req_addr,
                wake_handle: a32(0x17),
                proof: proof.to_vec(),
                token: sample_token.clone(),
            },
        ),
        (
            "slot.unsubscribe",
            wire::Request::SlotUnsubscribe {
                address: ep.address,
                wake_handle: a32(0x16),
            },
        ),
        (
            "shelf.take",
            wire::Request::ShelfTake {
                shelf: names::shelf_address(&id.public()),
            },
        ),
        ("blob.get", wire::Request::BlobGet { id: a32(0x18) }),
        (
            "name.lookup",
            wire::Request::NameLookup {
                localpart: "alice".into(),
            },
        ),
        (
            "name.register",
            wire::Request::NameRegister {
                card: signed.clone(),
                gate: vec![],
                token: sample_token.clone(),
            },
        ),
        (
            "backup.get",
            wire::Request::BackupGet {
                label: a32(0x19),
                index: 3,
            },
        ),
        (
            "wrap.get",
            wire::Request::WrapGet {
                username: "@alice:sigil.example".into(),
            },
        ),
        ("tpm.info", wire::Request::TpmInfo),
        (
            "token.issue",
            wire::Request::TokenIssue {
                credential: b"cred".to_vec(),
                blinded: vec![pending.blinded.clone()],
            },
        ),
        ("server.info", wire::Request::ServerInfo),
        (
            "requests.put",
            wire::Request::RequestsPut {
                address: req_address,
                envelope: req_env.clone(),
                token: sample_token.clone(),
            },
        ),
    ];
    let mut wreq = serde_json::Map::new();
    for (name, r) in &reqs {
        let enc = r.encode();
        assert_eq!(&wire::Request::decode(&enc).unwrap(), r);
        wreq.insert(name.to_string(), json!(h(&enc)));
    }
    let resps = vec![
        (
            "slot.put",
            wire::Op::SlotPut,
            wire::Response::SlotPut { seq: 42 },
        ),
        (
            "slot.get",
            wire::Op::SlotGet,
            wire::Response::SlotGet {
                items: vec![wire::Stored {
                    seq: 42,
                    envelope: sealed.clone(),
                }],
                more: false,
            },
        ),
        ("slot.ack", wire::Op::SlotAck, wire::Response::Empty),
        (
            "error.not_found",
            wire::Op::BlobGet,
            wire::Response::Error(wire::Status::NotFound),
        ),
        (
            "error.token_spent",
            wire::Op::SlotPut,
            wire::Response::Error(wire::Status::TokenSpent),
        ),
        (
            "blob.put",
            wire::Op::BlobPut,
            wire::Response::BlobPut { id: a32(0x18) },
        ),
        (
            "wrap.get",
            wire::Op::WrapGet,
            wire::Response::WrapGet {
                salt: [0x0b; 16],
                wrap: wrap.clone(),
            },
        ),
        (
            "token.issue",
            wire::Op::TokenIssue,
            wire::Response::TokenIssue {
                blind_sigs: vec![blind_sig.clone()],
            },
        ),
    ];
    let mut wresp = serde_json::Map::new();
    for (name, op, r) in &resps {
        let enc = r.encode();
        assert_eq!(&wire::Response::decode(*op, &enc).unwrap(), r);
        wresp.insert(name.to_string(), json!(h(&enc)));
    }
    let card = wire::ServerCard {
        hostname: "sigil.example".into(),
        kem_pub: server.public().to_vec(),
        token_key: issuer.spki.clone(),
        flags: 0b011,
        signing_pub: id.public(),
    };
    let card_enc = card.encode();
    assert_eq!(wire::ServerCard::decode(&card_enc).unwrap(), card);
    let frames = vec![
        (
            "bag",
            wire::Frame::Bag {
                id: 7,
                server: "sigil.example".into(),
                bind_handle: Some(a32(0x16)),
                bag: bag_bytes.clone(),
            },
        ),
        (
            "bag.nobind",
            wire::Frame::Bag {
                id: 8,
                server: "sigil.example".into(),
                bind_handle: None,
                bag: bag_bytes.clone(),
            },
        ),
        (
            "bag.response",
            wire::Frame::BagResponse {
                id: 7,
                response: resp.clone(),
            },
        ),
        (
            "deliver",
            wire::Frame::Deliver {
                wake_handle: a32(0x16),
                queue_seq: 9,
                envelope: sealed.clone(),
            },
        ),
        (
            "ack",
            wire::Frame::Ack {
                wake_handle: a32(0x16),
                queue_seq: 9,
            },
        ),
        (
            "push",
            wire::Frame::Push {
                kind: 3,
                token: b"https://push.example/up/abc".to_vec(),
            },
        ),
        (
            "release",
            wire::Frame::Release {
                wake_handle: a32(0x16),
            },
        ),
    ];
    let mut wfr = serde_json::Map::new();
    for (name, f) in &frames {
        let enc = f.encode();
        assert_eq!(&wire::Frame::decode(&enc).unwrap(), f);
        wfr.insert(name.to_string(), json!(h(&enc)));
    }
    v.insert(
        "wire".into(),
        json!({
            "requests": wreq,
            "responses": wresp,
            "frames": wfr,
            "server_card": h(&card_enc),
            "chunk_len": wire::CHUNK_LEN,
        }),
    );

    let _ = fill(0, 0);
    println!(
        "{}",
        serde_json::to_string_pretty(&Value::Object(v)).unwrap()
    );
}
